    'Skipped (Gaussian fit failure):           %d\n', ...
    skipBadFit);

fprintf(fid, ...
    'Skipped (invalid Gaussian sigma):         %d\n', ...
    skipInvalidSigma);

fprintf(fid, ...
    'Skipped (event threshold > %.1f):          %d\n', ...
