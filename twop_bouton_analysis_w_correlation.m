for idx = 1:numSelectedClusters

    k = selectedClusters(idx);

    events = allEventFrames{k};

    if isempty(events)
        continue;
    end

    temp = [ ...
        repmat(k, size(events,1), 1), ...
        (1:size(events,1))', ...
        events];

    eventFramesTable = ...
        [eventFramesTable; temp]; %#ok<AGROW>

end


